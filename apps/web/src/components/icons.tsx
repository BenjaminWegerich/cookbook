/**
 * Shared UI symbols.
 *
 * ONE symbol source for the whole app, so unrelated controls cannot drift into
 * different icon styles (decided with the user after the first mixed set):
 * every path below is taken verbatim from
 *
 *   google/material-design-icons -> symbols/android/<name>/materialsymbolsrounded/<name>_24px.xml
 *
 * i.e. **Material Symbols, Rounded style, 24 dp grid, weight 400, grade 0,
 * optical size 24, unfilled** — the same settings for every icon. The paths
 * use that family's native 960 x 960 coordinate system (viewBox
 * `0 0 960 960`; the drawables' y values run 0..960 top-down, so a negative
 * y origin would place every glyph outside the visible box), and
 * `fill="currentColor"` makes each glyph follow the
 * text color of its button or tag.
 *
 * Rules:
 * - an icon is always decorative (`aria-hidden`): it either sits next to a
 *   visible label or its button carries an `aria-label`;
 * - never mix in a filled or differently weighted glyph (e.g. no filled star
 *   next to an outlined one) — if a state must differ, express it with color;
 * - the rendered size comes from the pixel ladder via CSS (`--space-5` = 14 px
 *   inside tags, `--space-6` = 18 px inside buttons, `--icon-size` = 24 px for
 *   standalone symbols).
 */

/** The class name of the symbol's `<svg>` (undefined = sized by its context). */
interface IconProps {
  className?: string;
}

/** Attributes every symbol shares (the 960-unit Rounded grid).
 *
 * The explicit `width`/`height` are the fallback that keeps a symbol usable
 * without any CSS: an SVG with only a `viewBox` falls back to the replaced
 * element default of 300 x 150 px, which would blow up a button and push its
 * label out of sight (that is exactly what happened when the icons were first
 * swapped in). 24 px is the ladder's inline icon size; component rules such as
 * `.button-icon` (18 px) or `.tag-icon` (14 px) override it by class. */
const ICON_PROPS = {
  viewBox: '0 0 960 960',
  width: 24,
  height: 24,
  'aria-hidden': true,
  focusable: 'false',
} as const;

